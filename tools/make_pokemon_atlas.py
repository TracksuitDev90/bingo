# Builds the Pokémon edition's sprite sheet and Pokédex data:
#
#   assets/pokemon/sprites.webp  every Pokémon #001-#251, cropped and packed
#   js/pokemon/pokedex-data.js   their names and where each sits in the sheet
#
# The sprites are the Black/White (Gen 5) ones, the same set pokemondb.net
# shows, fetched from PokeAPI's sprite mirror on GitHub. Names come from
# PokeAPI's species data. Downloads are cached in tools/.cache/.
#
# Run from the repo root: python3 tools/make_pokemon_atlas.py  (needs Pillow)
import csv
import io
import json
import urllib.request
from pathlib import Path

from PIL import Image

LAST = 251
SPRITE = "https://raw.githubusercontent.com/PokeAPI/sprites/master/sprites/pokemon/versions/generation-v/black-white/{}.png"
NAMES = "https://raw.githubusercontent.com/PokeAPI/pokeapi/master/data/v2/csv/pokemon_species_names.csv"
ENGLISH = "9"
SHEET_W = 1024
PAD = 2  # transparent gutter so neighbours never bleed into each other

root = Path(__file__).resolve().parent.parent
cache = root / "tools" / ".cache"
cache.mkdir(parents=True, exist_ok=True)


def fetch(url, name):
    path = cache / name
    if not path.exists():
        with urllib.request.urlopen(url) as r:
            path.write_bytes(r.read())
    return path.read_bytes()


names = {}
for row in csv.DictReader(io.StringIO(fetch(NAMES, "species_names.csv").decode("utf-8"))):
    dex = int(row["pokemon_species_id"])
    if row["local_language_id"] == ENGLISH and dex <= LAST:
        names[dex] = row["name"]
assert len(names) == LAST, len(names)

sprites = {}
for dex in range(1, LAST + 1):
    im = Image.open(io.BytesIO(fetch(SPRITE.format(dex), f"bw-{dex}.png"))).convert("RGBA")
    # Some sprites have stray near-invisible pixels; crop to what can be seen.
    alpha = im.getchannel("A").point(lambda a: 255 if a > 24 else 0)
    sprites[dex] = im.crop(alpha.getbbox())

# Shelf packing, tallest first.
order = sorted(sprites, key=lambda d: (-sprites[d].height, -sprites[d].width))
rects = {}
x = y = shelf = 0
for dex in order:
    w, h = sprites[dex].size
    if x + w + PAD > SHEET_W:
        x = 0
        y += shelf + PAD
        shelf = 0
    rects[dex] = (x + PAD, y + PAD, w, h)
    x += w + PAD
    shelf = max(shelf, h + PAD)
height = y + shelf + PAD

sheet = Image.new("RGBA", (SHEET_W, height), (0, 0, 0, 0))
for dex, (rx, ry, _, _) in rects.items():
    sheet.alpha_composite(sprites[dex], (rx, ry))
out = root / "assets" / "pokemon"
out.mkdir(parents=True, exist_ok=True)
# Lossless WebP keeps every pixel and is a third the size of the PNG.
sheet.save(out / "sprites.webp", lossless=True, method=6, quality=100)

flat = [v for dex in range(1, LAST + 1) for v in rects[dex]]
js = f"""// Generated by tools/make_pokemon_atlas.py. Do not edit by hand.
//
// NAMES[dex - 1] is the English name of Pokémon #dex. RECTS holds four
// numbers per Pokémon (x, y, width, height) locating its sprite in
// assets/pokemon/sprites.webp, which is SHEET_W x SHEET_H pixels.

export const SHEET_W = {SHEET_W};
export const SHEET_H = {height};
export const NAMES = {json.dumps([names[d] for d in range(1, LAST + 1)], ensure_ascii=False)};
export const RECTS = new Uint16Array({json.dumps(flat, separators=(",", ":"))});
"""
(root / "js" / "pokemon").mkdir(parents=True, exist_ok=True)
(root / "js" / "pokemon" / "pokedex-data.js").write_text(js, encoding="utf-8")
print(f"sheet {SHEET_W}x{height}, {(out / 'sprites.webp').stat().st_size // 1024} KB")
